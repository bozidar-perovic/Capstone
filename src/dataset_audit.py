"""Dataset quality audit and cross-split overlap verification tool.

Provides automated checks for dataset integrity in FlakeBench splits:
- Validates schema columns, category ranges, and label-category alignment.
- Scans source code for structural anomalies (unbalanced braces,
  missing bodies).
- Detects test annotations and setup/teardown lifecycle methods.
- Computes deterministic source hashes to identify code duplicates and
  label conflicts.
- Audits cross-split overlap (project disjointness, test identities,
  source leakage, shared method names, and ID collisions).

Typical usage:
    python -m src.dataset_audit
    python -m src.dataset_audit --folds 1 2
    python -m src.dataset_audit --files src/data/FlakeBench_dataset.csv
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd

# =============================================================================
# Constants & Configuration
# =============================================================================

# Canonical mapping from integer category codes to human-readable labels.
# Category 5 corresponds to non-flaky tests; categories 0-4 represent
# specific types of test flakiness.
LABELS: Dict[int, str] = {
    0: "async wait",
    1: "concurrency",
    2: "time",
    3: "unordered collections",
    4: "test order dependency",
    5: "non-flaky",
}

# Minimum set of columns required for a dataset file to be auditable.
REQUIRED = {"id", "project", "test_name", "full_code", "label", "category"}

# Tokenizer regular expression. Matches multiline strings, string literals,
# character literals, single-line comments, block comments, identifiers,
# numbers, and non-whitespace punctuation.
# Literals are tokenized BEFORE comments so URLs (e.g., "http://...") and
# comment-like markers inside string literals remain literals.
TOKENS = re.compile(
    r'"""[\s\S]*?(?:"""|\Z)|"(?:\\.|[^"\\])*(?:"|\Z)'
    r"|'(?:\\.|[^'\\])*(?:'|\Z)|//[^\n]*|/\*[\s\S]*?(?:\*/|\Z)"
    r"|[A-Za-z_$][\w$]*|\d+(?:\.\d+)*|[^\s]"
)

# Regular expression matching standard JUnit 4/5 lifecycle annotations.
LIFECYCLE = re.compile(
    r"@(?:[\w$]+\.)*(?:Before|After|BeforeEach|AfterEach|BeforeAll|AfterAll|"
    r"BeforeClass|AfterClass)\b"
)

# Regular expression matching recognized test execution annotations.
TEST = re.compile(
    r"@(?:[\w$]+\.)*(?:Test|ParameterizedTest|RepeatedTest|TestFactory|"
    r"TestTemplate)\b"
)

# Column schemas for CSV reports generated by the audit process.
ISSUE_COLUMNS = [
    "file", "row_number", "id", "project", "test_name", "issue", "detail"
]
DUPLICATE_COLUMNS = [
    "file", "row_number", "id", "project", "test_name", "source_hash",
    "group_size", "binary_label_conflict", "category"
]
OVERLAP_COLUMNS = ["fold", "kind", "value"]


# =============================================================================
# Tokenization & Normalization Helpers
# =============================================================================

def source_tokens(source: str) -> List[str]:
    """Tokenize Java source code and discard developer comments.

    Args:
        source: Raw Java method source code string.

    Returns:
        List of non-comment tokens, preserving literal contents, identifiers,
        and syntax symbols.
    """
    return [
        token for token in TOKENS.findall(source)
        if not token.startswith(("//", "/*"))
    ]


def executable_text(tokens: List[str]) -> str:
    """Mask string/char literals so internal characters do not affect checks.

    Replaces literal string values with empty double quotes to prevent
    braces or annotations inside literals from interfering with structural
    heuristic scanning.

    Args:
        tokens: Cleaned token stream from source_tokens.

    Returns:
        Space-separated string of tokens with literal values masked.
    """
    return " ".join(
        '""' if token.startswith(('"', "'")) else token
        for token in tokens
    )


def hash_source(source: Any) -> Optional[str]:
    """Compute a deterministic SHA-256 hash for normalized Java source code.

    Strips comments and serializes token sequences to JSON before hashing.
    This produces identical hashes for methods that share identical code
    logic, variable names, and literals regardless of whitespace,
    indentation, or comments.

    Args:
        source: Java method source code string.

    Returns:
        Hexadecimal SHA-256 digest string, or None if the source is empty
        or non-text.
    """
    if not isinstance(source, str) or not source.strip():
        return None
    tokens = source_tokens(source)
    if not tokens:
        return None
    # JSON encoding preserves intra-token contents while enforcing standard
    # delimiter representation without collapsing distinct tokens.
    normalized = json.dumps(tokens, ensure_ascii=True)
    return hashlib.sha256(normalized.encode()).hexdigest()


# =============================================================================
# Single-File Quality Audit
# =============================================================================

def audit_frame(
    data: pd.DataFrame, file_name: str
) -> Tuple[Dict[str, Any], List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Audit a single dataset DataFrame for structural and schema issues.

    Checks logical CSV records (where row 1 is the header and row 2 is the
    first data record) for missing fields, invalid categories, label
    mismatches, syntax anomalies, and internal duplicate code groups.

    Args:
        data: Input DataFrame containing the test dataset records.
        file_name: File path or identifier string for reporting.

    Returns:
        Tuple of (summary_dict, row_issues_list, duplicate_members_list).
    """
    issues: List[Dict[str, Any]] = []
    missing = sorted(REQUIRED - set(data.columns))
    summary: Dict[str, Any] = {"rows": len(data), "missing_columns": missing}

    # If mandatory schema columns are absent, abort row-level checks early.
    if missing:
        issues.append(
            dict(
                zip(
                    ISSUE_COLUMNS,
                    [
                        file_name, None, None, None, None, "missing_columns",
                        ", ".join(missing),
                    ],
                )
            )
        )
        return summary, issues, []

    categories = pd.to_numeric(data["category"], errors="coerce")
    summary["category_counts"] = {
        str(key): int(value)
        for key, value in data["category"].value_counts(dropna=False).items()
    }
    groups: Dict[str, List[Dict[str, Any]]] = {}

    # Iterate through records; position starts at 2 to represent 1-based CSV
    # logical row numbers including the header row.
    for position, (_, row) in enumerate(data.iterrows(), start=2):
        identity = {
            "file": file_name,
            "row_number": position,
            **{key: row[key] for key in ("id", "project", "test_name")},
        }

        def flag(issue: str, detail: str) -> None:
            issues.append({**identity, "issue": issue, "detail": detail})

        # Validate category range and label alignment.
        category = categories.iloc[position - 2]
        valid = pd.notna(category) and category in LABELS
        if not valid:
            flag(
                "invalid_category",
                "Expected an integer category from 0 to 5",
            )
        elif pd.isna(row["label"]) or row["label"] != LABELS[category]:
            flag(
                "label_category_mismatch",
                f"Category {int(category)} expects {LABELS[category]!r}",
            )

        # Source code presence and validity check.
        source = row["full_code"]
        if not isinstance(source, str) or not source.strip():
            flag("missing_source", "Missing, non-text or blank full_code")
            continue

        tokens = source_tokens(source)
        if not tokens:
            flag("comment_only_source", "No code remains after comments")
            continue

        text = executable_text(tokens)
        annotation_text = re.sub(r"\s*([@.])\s*", r"\1", text)

        # Flag setup/teardown methods erroneously marked as test methods.
        if LIFECYCLE.search(annotation_text):
            flag("lifecycle_method", "Setup/teardown annotation detected")

        # Heuristic check: warn if no standard test annotation is found.
        if not TEST.search(annotation_text):
            flag(
                "no_recognized_test_annotation",
                "Heuristic: custom annotations/conventions may be valid",
            )

        # Verify curly brace balance to detect truncated method fragments.
        depth = 0
        unbalanced = False
        for token in tokens:
            if token == "{":
                depth += 1
            elif token == "}":
                depth -= 1
                if depth < 0:
                    unbalanced = True

        if depth != 0 or unbalanced:
            flag(
                "unbalanced_braces",
                "Heuristic: possible truncated or malformed method body",
            )
        elif "{" not in tokens:
            flag("missing_method_body", "Heuristic: no opening brace found")

        # Compute deterministic source hash for duplicate grouping.
        normalized = json.dumps(tokens, ensure_ascii=True)
        source_hash = hashlib.sha256(normalized.encode()).hexdigest()
        groups.setdefault(source_hash, []).append(
            {
                **identity,
                "source_hash": source_hash,
                "category": int(category) if valid else None,
            }
        )

    # Identify duplicate groups within the file and flag binary label
    # conflicts (where identical source is labeled both flaky and non-flaky).
    duplicates: List[Dict[str, Any]] = []
    for members in groups.values():
        if len(members) < 2:
            continue
        binary_labels = {
            item["category"] != 5
            for item in members
            if item["category"] is not None
        }
        conflict = len(binary_labels) > 1
        for member in members:
            duplicates.append(
                {
                    **member,
                    "group_size": len(members),
                    "binary_label_conflict": conflict,
                }
            )

    summary["issue_counts"] = {
        key: int(value)
        for key, value in pd.Series(
            [item["issue"] for item in issues], dtype=str
        )
        .value_counts()
        .items()
    }
    summary["duplicate_groups"] = len({d["source_hash"] for d in duplicates})
    summary["conflicting_duplicate_groups"] = len(
        {d["source_hash"] for d in duplicates if d["binary_label_conflict"]}
    )
    return summary, issues, duplicates


# =============================================================================
# Cross-Split Overlap & Leakage Audit
# =============================================================================

def audit_overlap(
    train: pd.DataFrame, test: pd.DataFrame, fold: int
) -> List[Dict[str, Any]]:
    """Audit cross-split overlap and data leakage between train and test sets.

    Inspects 5 distinct overlap dimensions:
    1. Project overlap: Shared projects across splits.
    2. Test identity: Complete (id, project, test_name) tuples.
    3. Source hash: Identical normalized source code (test set leakage).
    4. Conflicting source hash: Shared code with opposite binary labels.
    5. Test name: Shared test method names across projects.
    6. ID collisions: Shared numeric IDs across projects.

    Args:
        train: Training fold DataFrame.
        test: Held-out test fold DataFrame.
        fold: Fold index number.

    Returns:
        List of overlap records formatted with fold, kind, and JSON value.
    """
    overlaps: List[Dict[str, Any]] = []

    # 1. Project overlap: Verify project disjointness in Group K-Fold splits.
    if "project" in train.columns and "project" in test.columns:
        left = set(train["project"].dropna().unique())
        right = set(test["project"].dropna().unique())
        for value in sorted(left & right, key=str):
            overlaps.append(
                {
                    "fold": fold,
                    "kind": "project",
                    "value": json.dumps(value, default=str),
                }
            )

    # 2. Complete test identity: Check (id, project, test_name) tuple.
    identity_cols = ["id", "project", "test_name"]
    if (
        set(identity_cols).issubset(train.columns)
        and set(identity_cols).issubset(test.columns)
    ):
        left_tuples = set(
            train[identity_cols].dropna().itertuples(index=False, name=None)
        )
        right_tuples = set(
            test[identity_cols].dropna().itertuples(index=False, name=None)
        )
        for value in sorted(left_tuples & right_tuples, key=str):
            overlaps.append(
                {
                    "fold": fold,
                    "kind": "test_identity",
                    "value": json.dumps(value, default=str),
                }
            )

    # 3. Source code hash overlap: Detect test leakage across project forks.
    if "full_code" in train.columns and "full_code" in test.columns:
        train_hashes: Dict[str, set] = {}
        for _, row in train.iterrows():
            h = hash_source(row["full_code"])
            if h:
                cat = None
                if "category" in row and pd.notna(row["category"]):
                    try:
                        cat = int(pd.to_numeric(row["category"]))
                    except (ValueError, TypeError):
                        pass
                train_hashes.setdefault(h, set()).add(cat)

        test_hashes: Dict[str, set] = {}
        for _, row in test.iterrows():
            h = hash_source(row["full_code"])
            if h:
                cat = None
                if "category" in row and pd.notna(row["category"]):
                    try:
                        cat = int(pd.to_numeric(row["category"]))
                    except (ValueError, TypeError):
                        pass
                test_hashes.setdefault(h, set()).add(cat)

        common_hashes = sorted(set(train_hashes) & set(test_hashes))
        for h in common_hashes:
            overlaps.append(
                {
                    "fold": fold,
                    "kind": "source_hash",
                    "value": json.dumps(h),
                }
            )
            # Check if identical code has opposite labels across splits.
            tr_binary = {
                c != 5
                for c in train_hashes[h]
                if c is not None and c in LABELS
            }
            te_binary = {
                c != 5
                for c in test_hashes[h]
                if c is not None and c in LABELS
            }
            if (tr_binary | te_binary) == {True, False}:
                overlaps.append(
                    {
                        "fold": fold,
                        "kind": "conflicting_source_hash",
                        "value": json.dumps(h),
                    }
                )

    # 4. Test method name overlap: Track common method names across projects.
    if "test_name" in train.columns and "test_name" in test.columns:
        left = set(train["test_name"].dropna().unique())
        right = set(test["test_name"].dropna().unique())
        for value in sorted(left & right, key=str):
            overlaps.append(
                {
                    "fold": fold,
                    "kind": "test_name",
                    "value": json.dumps(value, default=str),
                }
            )

    # 5. ID overlap: Detect ID collisions across independent projects.
    if "id" in train.columns and "id" in test.columns:
        left = set(train["id"].dropna().unique())
        right = set(test["id"].dropna().unique())
        for value in sorted(left & right, key=str):
            # Normalize numeric ID values to prevent nested quotes in CSV.
            clean_val = int(value) if str(value).isdigit() else value
            overlaps.append(
                {
                    "fold": fold,
                    "kind": "id",
                    "value": json.dumps(clean_val, default=str),
                }
            )

    return overlaps


# =============================================================================
# CLI Entry Point
# =============================================================================

def main(argv=None):
    """Run dataset quality audit from the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-dir", type=Path, default=Path("src/data"),
        help="Directory containing the CSV dataset files",
    )
    parser.add_argument(
        "--folds", type=int, nargs="+", default=[1, 2, 3, 4],
        help="Fold numbers to audit as train/test pairs",
    )
    parser.add_argument(
        "--files", type=Path, nargs="+",
        help="Audit specific standalone CSV files instead of fold pairs",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=Path("src/results/dataset_audit"),
        help="Directory to write output CSV and JSON reports",
    )
    args = parser.parse_args(argv)

    paths = args.files or [
        args.data_dir / f"{split}_set_{fold}.csv"
        for fold in args.folds
        for split in ("train", "test")
    ]

    # Guard against accidental overwrite of input datasets.
    outputs = [
        args.output_dir / name
        for name in (
            "summary.json",
            "row_issues.csv",
            "duplicate_sources.csv",
            "fold_overlap.csv",
        )
    ]
    if set(p.resolve() for p in paths) & set(p.resolve() for p in outputs):
        parser.error("Report paths must not overwrite input files")

    summaries: Dict[str, Any] = {}
    frames: Dict[Path, pd.DataFrame] = {}
    issues: List[Dict[str, Any]] = []
    duplicates: List[Dict[str, Any]] = []

    # Process each unique dataset file.
    for path in dict.fromkeys(paths):
        print(f"Auditing {path}...", flush=True)
        data = pd.read_csv(path)
        summary, row_issues, members = audit_frame(data, str(path))
        summaries[str(path)] = summary
        frames[path] = data
        issues.extend(row_issues)
        duplicates.extend(members)
        print(
            f"  {len(data)} rows; {len(row_issues)} issues; "
            f"{summary.get('conflicting_duplicate_groups', 0)} "
            "conflicting source groups"
        )

    # Perform cross-split overlap checks for cross-validation pairs.
    overlaps: List[Dict[str, Any]] = []
    if not args.files:
        for fold in args.folds:
            overlaps.extend(
                audit_overlap(
                    frames[args.data_dir / f"train_set_{fold}.csv"],
                    frames[args.data_dir / f"test_set_{fold}.csv"],
                    fold,
                )
            )

    args.output_dir.mkdir(parents=True, exist_ok=True)

    overlap_counts_by_kind = (
        {
            key: int(val)
            for key, val in pd.Series(
                [item["kind"] for item in overlaps], dtype=str
            )
            .value_counts()
            .items()
        }
        if overlaps
        else {}
    )

    report = {
        "note": (
            "Read-only audit. Heuristic flags are not confirmed errors. "
            "Duplicates are grouped within each input file, not across "
            "overlapping training folds. Cross-split overlaps check "
            "project, identity, source hash, test name, and ID. "
            "No labels were changed."
        ),
        "files": summaries,
        "fold_overlap_count": len(overlaps),
        "fold_overlap_by_kind": overlap_counts_by_kind,
    }

    # Write audit reports to the designated output directory.
    outputs[0].write_text(json.dumps(report, indent=2, default=str) + "\n")
    pd.DataFrame(issues, columns=ISSUE_COLUMNS).to_csv(
        outputs[1], index=False
    )
    pd.DataFrame(duplicates, columns=DUPLICATE_COLUMNS).to_csv(
        outputs[2], index=False
    )
    pd.DataFrame(overlaps, columns=OVERLAP_COLUMNS).to_csv(
        outputs[3], index=False
    )
    print(
        f"Saved audit reports to {args.output_dir}; "
        f"{len(overlaps)} fold overlap entries. Inputs unchanged."
    )


if __name__ == "__main__":
    main()
